#!/usr/bin/env python
"""Filter one template bank against many (detector, GPS chunk) datasets held on one GPU.

Each dataset is conditioned once with PyCBC's own code (read, high-pass, resample, gate,
segment, PSD), in parallel CPU processes. All of them then stay on the GPU, and each batch
of templates is made once and filtered against every dataset: matched filter, fused peak
finding, chi-squared kernel at peaks, gate veto. Non-SPA templates come from a coarse
frequency grid on the CPU, interpolated onto the fine grid on the GPU (imr_interp.py);
SPAtmplt is generated by PyCBC on the GPU.

Usage:
  multi_filter.py --datasets datasets.txt --bank BANK.hdf --approximant IMRPhenomD \\
      --argv inspiral_argv.txt --out OUTDIR [--batch 128] [--prep-procs 8] -- [pycbc options]
datasets.txt: one "IFO GPS_START GPS_END STORE.hdf" per line (store as written by chunk_prep.py).
Writes OUTDIR/peaks/IFO-START-END.hdf per dataset (same fields as batched_filter.py) and
OUTDIR/timing.json. Run with OMP_NUM_THREADS=1.
"""
import argparse, json, os, shlex, sys, time
from concurrent.futures import ThreadPoolExecutor
from multiprocessing import Pool
from types import SimpleNamespace
import numpy as np
import h5py

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def pycbc_parser():
    import pycbc.strain, pycbc.psd, pycbc.fft
    p = argparse.ArgumentParser()
    pycbc.psd.insert_psd_option_group(p)
    pycbc.strain.insert_strain_option_group(p)
    pycbc.strain.StrainSegments.insert_segment_option_group(p)
    pycbc.fft.insert_fft_option_group(p)
    p.add_argument('--bank-file'); p.add_argument('--approximant', nargs='+')
    p.add_argument('--order', type=int, default=-1)
    p.add_argument('--low-frequency-cutoff', type=float)
    p.add_argument('--snr-threshold', type=float)
    p.add_argument('--cluster-window', type=float)
    p.add_argument('--chisq-bins', default='0')
    p.add_argument('--chisq-snr-threshold', type=float)
    return p


def setopt(av, k, v):
    av = list(av)
    if k in av:
        av[av.index(k) + 1] = v
    else:
        av += [k, v]
    return av


def getopt(av, k, default):
    return float(av[av.index(k) + 1]) if k in av else default


def dataset_argv(base, ifo, s, e, store):
    pad = getopt(base, '--pad-data', 8); sp = getopt(base, '--segment-start-pad', 144); ep = getopt(base, '--segment-end-pad', 16)
    av = base
    for k, v in (('--hdf-store', store), ('--channel-name', f'{ifo}:GWOSC_STRAIN'),
                 ('--gps-start-time', str(int(s + pad))), ('--gps-end-time', str(int(e - pad))),
                 ('--trig-start-time', str(int(s + pad + sp))), ('--trig-end-time', str(int(e - pad - ep)))):
        av = setopt(av, k, v)
    return av


def prep_one(job):
    """Runs in a worker process: condition one dataset, save whitened segments to npz."""
    tag, argv, outdir = job
    t0 = time.perf_counter()
    import pycbc, pycbc.strain, pycbc.psd, pycbc.fft
    from pycbc import DYN_RANGE_FAC
    opt, _ = pycbc_parser().parse_known_args(argv)
    opt.injection_file = None
    pycbc.fft.from_cli(opt)
    gw = pycbc.strain.from_cli(opt, dyn_range_fac=DYN_RANGE_FAC)
    ss = pycbc.strain.StrainSegments.from_cli(opt, gw)
    segs = ss.fourier_segments()
    flen, tlen, df = ss.freq_len, ss.time_len, ss.delta_f
    flow = opt.low_frequency_cutoff
    pycbc.psd.associate_psds_to_segments(opt, segs, gw, flen, df, flow, dyn_range_factor=DYN_RANGE_FAC, precision='single')
    kmin = int(flow / df)
    ipsd = np.stack([seg.psd.numpy() for seg in segs]).astype(np.float64)
    with np.errstate(divide='ignore'):
        ipsd = np.where(ipsd > 0, 1.0 / ipsd, 0.0)
    ipsd[:, :kmin] = 0
    D = (np.stack([seg.numpy() for seg in segs]) * ipsd).astype(np.complex64)
    fn = os.path.join(outdir, tag + '.npz')
    np.savez(fn, D=D, IP=ipsd.astype(np.float32))
    gates = [tuple(map(float, g)) for kind in (gw.gating_info or {}).values() for g in kind]
    meta = dict(tag=tag, file=fn, flen=flen, tlen=tlen, df=df, sr=float(gw.sample_rate), gps_start=float(opt.gps_start_time),
                analyze=[(seg.analyze.start, seg.analyze.stop) for seg in segs], seg_start=[seg.seg_slice.start for seg in segs],
                gates=gates, prep_s=time.perf_counter() - t0)
    return meta


def main():
    split = sys.argv.index('--') if '--' in sys.argv else len(sys.argv)
    ap = argparse.ArgumentParser()
    ap.add_argument('--datasets', required=True); ap.add_argument('--bank', required=True)
    ap.add_argument('--approximant', required=True); ap.add_argument('--argv', required=True)
    ap.add_argument('--out', required=True); ap.add_argument('--batch', type=int, default=128)
    ap.add_argument('--prep-procs', type=int, default=8); ap.add_argument('--gen-threads', type=int, default=8)
    ap.add_argument('--n-chirp', type=int, default=6000); ap.add_argument('--n-log', type=int, default=1500)
    ap.add_argument('--max-templates', type=int)
    a = ap.parse_args(sys.argv[1:split])
    base = shlex.split(open(a.argv).read()) + sys.argv[split + 1:]
    base = setopt(setopt(base, '--bank-file', a.bank), '--approximant', a.approximant)
    T = dict(prep_s=0.0, load_s=0.0, templates_s=0.0, filter_s=0.0, chisq_s=0.0, n_chisq_points=0)
    t_start = time.perf_counter()
    for d in ('peaks', 'prep'):
        os.makedirs(os.path.join(a.out, d), exist_ok=True)

    # ---- condition all datasets in parallel on the CPU
    ds = [l.split() for l in open(a.datasets) if l.strip() and not l.startswith('#')]
    jobs = [(f'{i}-{s}-{e}', dataset_argv(base, i, int(s), int(e), st), os.path.join(a.out, 'prep')) for i, s, e, st in ds]
    t0 = time.perf_counter()
    with Pool(min(a.prep_procs, len(jobs))) as pool:
        metas = pool.map(prep_one, jobs, chunksize=1)
    T['prep_s'] = time.perf_counter() - t0
    T['prep_cpu_s_each'] = [m['prep_s'] for m in metas]

    import cupy as cp
    import pycbc, pycbc.scheme, pycbc.waveform
    from pycbc.types import complex64
    from pycbc.vetoes.chisq import SingleDetPowerChisq
    from pycbc.events.ranking import newsnr
    from chisq_kernel import bin_power_sums
    from peak_kernel import window_peaks
    from imr_interp import coarse_grid, coarse_generate, FineInterpolator
    sync = cp.cuda.Device().synchronize
    opt, _ = pycbc_parser().parse_known_args(base)
    chisq_bins = opt.chisq_bins.strip('"\'')
    do_chisq = chisq_bins not in ('', '0')

    t0 = time.perf_counter()
    for m in metas:
        z = np.load(m['file'])
        m['D'] = cp.asarray(z['D']); m['IP'] = cp.asarray(z['IP'])
        os.remove(m['file'])
        m['out'] = dict(tid=[], t=[], snr=[], chi=[], dof=[], ph=[], sg=[])
    flen, tlen, df = metas[0]['flen'], metas[0]['tlen'], metas[0]['df']
    assert all(m['flen'] == flen and m['tlen'] == tlen for m in metas)
    T['load_s'] = time.perf_counter() - t0
    T['gpu_mem_data_gib'] = sum(m['D'].nbytes + m['IP'].nbytes for m in metas) / 2 ** 30

    flow = opt.low_frequency_cutoff
    kmin = int(flow / df)
    gpu_spa = a.approximant == 'SPAtmplt'
    ctx = pycbc.scheme.CUPYScheme()
    with (ctx if gpu_spa else __import__('contextlib').nullcontext()):
        bank = pycbc.waveform.FilterBank(a.bank, flen, df, complex64, low_frequency_cutoff=flow,
                                         phase_order=opt.order, approximant=a.approximant)
    ntmp = len(bank) if a.max_templates is None else min(a.max_templates, len(bank))
    hashes = np.asarray(bank.table.template_hash)[:ntmp]
    nbins_all = np.zeros(ntmp, np.int64); kmax_all = np.zeros(ntmp, np.int64)
    if not gpu_spa:
        f_end = bank.end_frequency(0)
        kend = int(f_end / df) if f_end and f_end < (flen - 1) * df else flen - 1
        x = coarse_grid(flow, kend * df, a.n_chirp, a.n_log)
        interp = FineInterpolator(x, df, kmin, kend, flen, cp)
        gen_pool = ThreadPoolExecutor(1)

        def coarse(b0, b1):
            return coarse_generate([bank.table[i] for i in range(b0, b1)], x, a.approximant, flow, threads=a.gen_threads)
        nxt = gen_pool.submit(coarse, 0, min(a.batch, ntmp))
    T['max_phase_step_rad'] = 0.0

    qbuf = cp.zeros((a.batch, tlen), cp.complex64)
    cmul = cp.ElementwiseKernel('complex64 h, complex64 d', 'complex64 o', 'o = conj(h) * d', 'cmul_conj')
    cw = int(opt.cluster_window * metas[0]['sr'])
    for b0 in range(0, ntmp, a.batch):
        b1 = min(b0 + a.batch, ntmp); nb = b1 - b0
        t0 = time.perf_counter()
        if gpu_spa:
            with ctx:
                hs = []
                for i in range(b0, b1):
                    h = bank[i]; hs.append(h.data.copy()); kmax_all[i] = int(h.end_idx)
                Hd = cp.stack(hs)
        else:
            amp, ph, step = nxt.result()
            if b1 < ntmp:
                nxt = gen_pool.submit(coarse, b1, min(b1 + a.batch, ntmp))
            T['max_phase_step_rad'] = max(T['max_phase_step_rad'], step)
            Hd = interp(amp, ph)
            kmax_all[b0:b1] = kend
        for i in range(b0, b1):
            if do_chisq:
                nbins_all[i] = int(SingleDetPowerChisq.parse_option(SimpleNamespace(params=bank.table[i]), chisq_bins))
        sync()
        T['templates_s'] += time.perf_counter() - t0
        t0 = time.perf_counter()
        Pw = Hd.real ** 2 + Hd.imag ** 2
        for m in metas:
            sig = (4.0 * df) * (Pw @ m['IP'].T)                      # (nb, n_segments)
            norm = ((4.0 * df) / cp.sqrt(sig)).astype(cp.float32)
            for s, (a0, a1) in enumerate(m['analyze']):
                nwin = (a1 - a0) // cw
                qv = qbuf[:nb]
                cmul(Hd, m['D'][s], qv[:, :flen])
                z = cp.fft.ifft(qv, axis=1)                          # includes 1/N; scaled back below
                pmax, pidx = window_peaks(z, a0, cw, nwin)
                nr = norm[:, s] * float(tlen)
                pk = cp.sqrt(pmax) * nr[:, None]
                tb, wb = cp.nonzero(pk > opt.snr_threshold)
                samp = a0 + wb * cw + pidx[tb, wb]
                val = pk[tb, wb]
                zp = z[tb, samp]
                ph_ = cp.angle(zp); sg_ = sig[tb, s]
                tb, samp, val, ph_, sg_ = tb.get(), samp.get(), val.get(), ph_.get(), sg_.get()
                o = m['out']
                o['tid'].append(tb + b0); o['t'].append(m['gps_start'] + (m['seg_start'][s] + samp) / m['sr'])
                o['snr'].append(val); o['ph'].append(ph_.astype(np.float32)); o['sg'].append(sg_)
                if do_chisq:
                    tc = time.perf_counter()
                    chi = np.zeros(len(tb), np.float32)
                    dof = (2 * nbins_all[b0 + tb] - 2).astype(np.int32)
                    todo = np.nonzero(val > opt.chisq_snr_threshold)[0] if opt.chisq_snr_threshold else np.arange(len(tb))
                    if len(todo):
                        rows, tids = tb[todo], b0 + tb[todo]
                        E = edges_per_template(cp, rows, nbins_all[tids], kmin, kmax_all[tids], Hd, m['IP'][s])
                        pw = cp.asarray(bin_power_sums(qv, rows, samp[todo].astype(np.int64), E))
                        zt = z[cp.asarray(rows), cp.asarray(samp[todo])] * float(tlen)
                        nrm = norm[cp.asarray(rows), s]
                        chi[todo] = ((cp.asarray(nbins_all[tids]) * pw - cp.abs(zt) ** 2) * nrm ** 2).get()
                    o['chi'].append(chi); o['dof'].append(dof)
                    T['chisq_s'] += time.perf_counter() - tc
                    T['n_chisq_points'] += int(len(todo))
        sync()
        T['filter_s'] += time.perf_counter() - t0
        print(f'batch {b0 // a.batch + 1}/{-(-ntmp // a.batch)} templates {b1} elapsed {time.perf_counter() - t_start:.0f}s '
              f"gen {T['templates_s']:.0f} filter {T['filter_s']:.0f} chisq {T['chisq_s']:.0f}", flush=True)

    t0 = time.perf_counter()
    T['n_peaks'] = {}
    for m in metas:
        o = m['out']
        cat = lambda k, dt: np.concatenate(o[k]) if o[k] else np.array([], dt)
        tid, t, snr, ph, sg = cat('tid', int), cat('t', float), cat('snr', float), cat('ph', np.float32), cat('sg', float)
        keep = np.ones(len(snr), bool)
        for g_t, g_w, g_taper in m['gates']:
            keep &= np.abs(t - g_t) > g_w + g_taper + 0.5
        fn = os.path.join(a.out, 'peaks', m['tag'] + '.hdf')
        with h5py.File(fn + '.part', 'w') as f:
            f['template_id'] = tid[keep]; f['template_hash'] = hashes[tid[keep]]; f['snr'] = snr[keep]; f['end_time'] = t[keep]
            f['coa_phase'] = ph[keep]; f['peak_sigmasq'] = sg[keep]
            if do_chisq:
                chi, dof = cat('chi', np.float32)[keep], cat('dof', np.int32)[keep]
                f['chisq'] = chi; f['chisq_dof'] = dof; f['newsnr'] = newsnr(snr[keep], chi / np.maximum(dof, 1))
            f.attrs['n_gates'] = len(m['gates'])
        os.replace(fn + '.part', fn)
        T['n_peaks'][m['tag']] = int(keep.sum())
    T['write_s'] = time.perf_counter() - t0
    T['total_s'] = time.perf_counter() - t_start
    T.update(n_templates=ntmp, n_datasets=len(metas), batch=a.batch, approximant=a.approximant,
             data_ks=sum((a1 - a0) / m['sr'] for m in metas for a0, a1 in m['analyze']) / 1000)
    json.dump(T, open(os.path.join(a.out, 'timing.json'), 'w'), indent=1)
    print(json.dumps({k: v for k, v in T.items() if k not in ('n_peaks', 'prep_cpu_s_each')}))


def edges_per_template(xp, rows, nb_, kmin, k1, Hd, ips):
    """Equal-power chi-squared bin edges from each template's cumulative |h|^2/psd (pycbc's
    non-SPA rule), for all peaks at once: rows are normalised to [0, 1] and offset by their
    index in one flattened array, so a single searchsorted serves every row."""
    ur, inv = np.unique(rows, return_inverse=True)
    B = int(nb_.max())
    h = Hd[xp.asarray(ur)]
    cs = xp.cumsum((h.real.astype(xp.float64) ** 2 + h.imag.astype(xp.float64) ** 2) * ips[None, :].astype(xp.float64), axis=1)
    k1u = k1[np.unique(inv, return_index=True)[1]]
    tot = cs[xp.arange(len(ur)), xp.asarray(k1u) - 1]
    F = cs.shape[1]
    flat = (cs / tot[:, None] + xp.arange(len(ur), dtype=xp.float64)[:, None]).ravel()
    j = np.arange(B)[None, :]
    target = inv[:, None] + j / nb_[:, None]
    e = xp.searchsorted(flat, xp.asarray(target).ravel(), side='right').reshape(target.shape) - xp.asarray(inv[:, None]) * F
    e = e.get() if hasattr(e, 'get') else e
    e = np.clip(e, kmin, k1[:, None])
    e = np.where(j < nb_[:, None], e, k1[:, None])
    return np.concatenate([e, k1[:, None]], axis=1)


if __name__ == '__main__':
    main()
